var update = flag.Bool("update", false, "rewrite ../vectors/core.json")

const corePath = "../vectors/core.json"

func h(b []byte) string { return hex.EncodeToString(b) }

type boxVector struct {
	Name       string            `json:"name"`
	Series     string            `json:"series"`
	Meta       string            `json:"meta"`
	Size       int               `json:"size"`
	Props      map[string]string `json:"properties"`
	Payload    string            `json:"payload"`
	Entropy    string            `json:"entropy"`
	Plain      string            `json:"plain"`
	Nonce      string            `json:"nonce"`
	KeyInput   string            `json:"key_input"`
	OpenKey    string            `json:"open_key"`
	EncKey     string            `json:"enc_key"`
	KeyCommit  string            `json:"key_commit"`
	Ciphertext string            `json:"ciphertext"`
	ID         string            `json:"box_id"`
	Sig        string            `json:"sig"`
	Box        string            `json:"box"`
}

type rewriteVector struct {
	Of       string            `json:"of"`
	Revision uint32            `json:"revision"`
	Props    map[string]string `json:"properties"`
	Sig      string            `json:"sig"`
	Box      string            `json:"box"`
}

type drawVector struct {
	Name        string            `json:"name"`
	Blueprint   string            `json:"blueprint"`
	Props       map[string]string `json:"properties"`
	Input       string            `json:"input"`
	InputCommit string            `json:"input_commit"`
	Entropy     string            `json:"entropy"`
	Nonce       string            `json:"nonce"`
	KeyInput    string            `json:"key_input"`
	OpenKey     string            `json:"open_key"`
	KeyCommit   string            `json:"key_commit"`
	Ticket      string            `json:"ticket"`
	Item        string            `json:"item"`
	Plain       string            `json:"plain"`
	Ciphertext  string            `json:"ciphertext"`
	ID          string            `json:"box_id"`
	Box         string            `json:"box"`
}

type cappedVector struct {
	Name    string   `json:"name"`
	SoldOut []uint16 `json:"sold_out"`
	Input   string   `json:"input"`
	Entropy string   `json:"entropy"`
	Ticket  string   `json:"ticket"`
	OpenKey string   `json:"open_key"`
	Item    string   `json:"item"`
	Serial  uint64   `json:"serial"`
	Box     string   `json:"box"`
}

type blueprintVector struct {
	Series string `json:"series"`
	Meta   string `json:"meta"`
	Items  []Item `json:"items"`
	Total  uint64 `json:"total"`
	Size   int    `json:"size"`
	Hex    string `json:"hex"`
	ID     string `json:"id"`
}

func buildCore(t *testing.T) map[string]any {
	is := mustIssuer(t, 1, mainTag)
	v := map[string]any{
		"about": "Honeypot core conformance vectors, generated by `go test . -update` in go/. Hex strings; every box comes from the main key and its entropy. Signatures are deterministic ML-DSA-65.",
		"issuer": map[string]any{
			"key_id": is.KeyID, "main_key": h(seed(mainTag)), "public": h(is.Public()),
			"sign_seed": h(is.sign.Bytes()), "open_root": h(is.root),
		},
	}
	cases := []struct {
		name    string
		spec    Spec
		payload []byte
	}{
		{"common item, assigned to a user", assigned("alice"), []byte("wooden sword")},
		{"legendary item, same size on the wire", assigned("alice"), []byte("legendary sword, +9 to everything")},
		{"empty box, no properties", chest, nil},
		{"payload fills the size exactly, no meta", Spec{Series: "acme/coupon", Size: 7}, []byte("SAVE5")},
		{"no series, no meta", Spec{Size: 2}, nil},
		{"properties in byte order", Spec{Series: "acme/item", Size: 16, Props: map[string]string{"userId": "u1", "Level": "3", "é": "✓", "empty": ""}}, []byte("x")},
	}
	var boxes []boxVector
	var sealed []Box
	for _, c := range cases {
		plain, err := pad(c.payload, c.spec.Size)
		if err != nil {
			t.Fatal(err)
		}
		e := entropyOf(c.name)
		b := is.seal(e, c.spec, plain)
		id, in, key := b.ID(), b.keyInput(), is.Key(b)
		boxes = append(boxes, boxVector{c.name, c.spec.Series, h(c.spec.Meta), c.spec.Size, c.spec.Props, h(c.payload), h(e[:]), h(plain),
			h(b.Nonce[:]), h(in[:]), h(key), h(kdf(key, tagEnc)), h(b.KeyCommit[:]), h(b.Ciphertext), h(id[:]), h(b.Sig), h(b.Encode())})
		sealed = append(sealed, b)
	}
	v["boxes"] = boxes

	moved, err := is.Rewrite(newLedger(), sealed[0], map[string]string{PropUser: "bob", "traded": "1"})
	if err != nil {
		t.Fatal(err)
	}
	v["rewrites"] = []rewriteVector{{cases[0].name, moved.Revision, moved.Props, h(moved.Sig), h(moved.Encode())}}

	good := sealed[0].Encode()
	badFlagBytes := append([]byte(nil), good...)
	badFlagBytes[len(sealed[0].prefix())-1] = 2
	badFlag := h(badFlagBytes)
	flip := func(i int) string {
		bad := append([]byte(nil), good...)
		bad[i] ^= 1
		return h(bad)
	}
	props := func(p ...byte) string {
		raw := append(appendU32(sealed[0].sealed(), 0), p...)
		return h(append(raw, sealed[0].Sig...))
	}
	v["invalid"] = map[string]any{
		"undecodable": map[string]string{
			"empty":                   "",
			"wrong tag":               flip(0),
			"truncated":               h(good[:len(good)-1]),
			"trailing bytes":          h(append(append([]byte(nil), good...), 0)),
			"properties out of order": props(2, 1, 'b', 0, 0, 1, 'a', 0, 0),
			"duplicate property":      props(2, 1, 'a', 0, 0, 1, 'a', 0, 0),
			"empty property name":     props(1, 0, 0, 0),
			"binary property name":    props(1, 1, 0xff, 0, 0),
			"binary property value":   props(1, 1, 'a', 0, 1, 0xff),
			"bad draw flag":           badFlag,
		},
		"bad_signature": map[string]string{
			"flipped key id":        flip(8),
			"flipped nonce":         flip(len(sealed[0].prefix())),
			"flipped key commit":    flip(len(sealed[0].header())),
			"flipped ciphertext":    flip(len(sealed[0].sealed()) - 1),
			"flipped revision":      flip(len(sealed[0].sealed()) + 3),
			"flipped property":      flip(len(sealed[0].signed()) - 1),
			"flipped signature":     flip(len(good) - 1),
			"rewritten, not signed": h(append(appendProps(appendU32(sealed[0].sealed(), 1), moved.Props), sealed[0].Sig...)),
		},
		"wrong_key": map[string]string{
			"key of another box": h(is.Key(sealed[1])),
			"all zero":           h(make([]byte, KeySize)),
		},
	}
	gold := gold(t)
	even, err := NewBlueprint("acme/even", nil, []Item{{"a", 1, 0}, {"b", 1, 0}, {"c", 2, 0}})
	if err != nil {
		t.Fatal(err)
	}
	blueprints := map[string]Blueprint{"gold": gold, "even": even}
	bpv := map[string]blueprintVector{}
	for name, bp := range blueprints {
		id := bp.ID()
		bpv[name] = blueprintVector{bp.Series, h(bp.Meta), bp.Items, bp.Total(), bp.size(), h(bp.Encode()), h(id[:])}
	}
	v["blueprints"] = bpv

	var draws []drawVector
	for _, c := range []struct {
		name, bp string
		props    map[string]string
	}{
		{"draw 1", "gold", map[string]string{PropUser: "alice"}},
		{"draw 2", "gold", nil},
		{"draw 3", "even", nil},
		{"draw 4", "even", nil},
		{"draw 5", "even", map[string]string{PropUser: "bob"}},
		{"draw 6", "even", nil},
	} {
		bp := blueprints[c.bp]
		input, e := entropyOf(c.name+" input"), entropyOf(c.name+" entropy")
		commit := commitInput(input)
		ticket, err := is.Ticket(bytes.NewReader(e[:]), nil, bp, commit, c.props)
		if err != nil {
			t.Fatal(err)
		}
		b, err := is.Redeem(nil, ticket, bp, input)
		if err != nil {
			t.Fatal(err)
		}
		key, in, id := is.Key(b), b.keyInput(), b.ID()
		item := bp.pick(key, input, nil)
		plain, _ := pad(append(make([]byte, 8), item.ID...), bp.size())
		draws = append(draws, drawVector{c.name, c.bp, c.props, h(input[:]), h(commit[:]), h(e[:]), h(b.Nonce[:]), h(in[:]), h(key), h(b.KeyCommit[:]),
			h(ticket.Encode()), item.ID, h(plain), h(b.Ciphertext), h(id[:]), h(b.Encode())})
	}
	v["draws"] = draws

	limited, err := NewBlueprint("acme/limited", nil, []Item{{"plain", 1, 0}, {"rare", 9, 2}})
	if err != nil {
		t.Fatal(err)
	}
	id := limited.ID()
	bpv["limited"] = blueprintVector{limited.Series, h(limited.Meta), limited.Items, limited.Total(), limited.size(), h(limited.Encode()), h(id[:])}
	caps := newCaps()
	var capped []cappedVector
	for i := range 8 {
		name := fmt.Sprint("capped draw ", i)
		input, e := entropyOf(name+" input"), entropyOf(name+" entropy")
		ticket, err := is.Ticket(bytes.NewReader(e[:]), caps, limited, commitInput(input), nil)
		if err != nil {
			t.Fatal(err)
		}
		b, err := is.Redeem(caps, ticket, limited, input)
		if err != nil {
			t.Fatal(err)
		}
		drawn, err := b.OpenItem(is.keys(), limited, is.Key(b))
		if err != nil {
			t.Fatal(err)
		}
		capped = append(capped, cappedVector{name, ticket.SoldOut, h(input[:]), h(e[:]), h(ticket.Encode()), h(is.Key(b)), drawn.Item.ID, drawn.Serial, h(b.Encode())})
	}
	v["capped_draws"] = capped

	// The rule behind a draw, at totals no blueprint reaches, so a retry happens.
	type rollVector struct {
		Key, BlueprintID, Input string
		Total, R                string
		First                   string
	}
	var rolls []rollVector
	total := uint64(1<<63 + 1)
	for i := range 4 {
		key, id, input := seed(fmt.Sprint("roll key ", i)), entropyOf(fmt.Sprint("roll id ", i)), entropyOf(fmt.Sprint("roll input ", i))
		first := kdf(key, tagRoll, id[:], input[:], appendU32(nil, 0))
		rolls = append(rolls, rollVector{h(key), h(id[:]), h(input[:]), fmt.Sprint(total), fmt.Sprint(roll(key, id, input, total)), h(first[:8])})
	}
	v["rolls"] = rolls
	return v
}

func TestCoreVectors(t *testing.T) {
	b, _ := json.MarshalIndent(buildCore(t), "", " ")
	b = append(b, '\n')
	if *update {
		if err := os.WriteFile(corePath, b, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(corePath)
	if err != nil || string(got) != string(b) {
		t.Fatalf("vectors/core.json is stale (run go test . -update): %v", err)
	}
}

// Read the vectors the way another language would: from the hex, with no help
// from the code that wrote them.
func TestCoreVectorsVerify(t *testing.T) {
	raw, err := os.ReadFile(corePath)
	if err != nil {
		t.Fatal(err)
	}
	var f struct {
		Issuer struct {
			KeyID   uint8  `json:"key_id"`
			MainKey string `json:"main_key"`
			Public  string `json:"public"`
		} `json:"issuer"`
		Blueprints map[string]blueprintVector `json:"blueprints"`
		Draws      []drawVector               `json:"draws"`
		Capped     []cappedVector             `json:"capped_draws"`
		Boxes      []boxVector                `json:"boxes"`
		Rewrites   []rewriteVector            `json:"rewrites"`
		Invalid    struct {
			Undecodable  map[string]string `json:"undecodable"`
			BadSignature map[string]string `json:"bad_signature"`
			WrongKey     map[string]string `json:"wrong_key"`
		} `json:"invalid"`
	}
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	unhex := func(s string) []byte {
		b, err := hex.DecodeString(s)
		if err != nil {
			t.Fatal(err)
		}
		return b
	}
	keys := map[uint8][]byte{f.Issuer.KeyID: unhex(f.Issuer.Public)}
	is, err := NewIssuer(f.Issuer.KeyID, unhex(f.Issuer.MainKey))
	if err != nil || h(is.Public()) != f.Issuer.Public {
		t.Fatalf("issuer: %v", err)
	}
	for _, c := range f.Boxes {
		b, err := DecodeBox(unhex(c.Box))
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		if err := b.Verify(keys); err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		if h(is.Key(b)) != c.OpenKey {
			t.Fatalf("%s: open key", c.Name)
		}
		payload, err := b.Open(keys, unhex(c.OpenKey))
		if err != nil || h(payload) != c.Payload {
			t.Fatalf("%s: %x %v", c.Name, payload, err)
		}
		if len(b.Props) != len(c.Props) {
			t.Fatalf("%s: properties", c.Name)
		}
		for name, value := range c.Props {
			if b.Props[name] != value {
				t.Fatalf("%s: property %s", c.Name, name)
			}
		}
	}
	first, err := DecodeBox(unhex(f.Boxes[0].Box))
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range f.Rewrites {
		b, err := DecodeBox(unhex(c.Box))
		if err != nil {
			t.Fatalf("%s: %v", c.Of, err)
		}
		if err := b.Verify(keys); err != nil || !b.Supersedes(first) || b.Revision != c.Revision {
			t.Fatalf("%s: %v", c.Of, err)
		}
		payload, err := b.Open(keys, unhex(f.Boxes[0].OpenKey))
		if err != nil || h(payload) != f.Boxes[0].Payload {
			t.Fatalf("%s: the rewrite must open with the same key: %v", c.Of, err)
		}
	}
	for _, c := range f.Draws {
		pv := f.Blueprints[c.Blueprint]
		bp, err := DecodeBlueprint(unhex(pv.Hex))
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		ticket, err := DecodeTicket(unhex(c.Ticket))
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		if err := ticket.Verify(keys, bp, [32]byte(unhex(c.InputCommit))); err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		b, err := DecodeBox(unhex(c.Box))
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		if err := b.VerifyTicket(keys, ticket); err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		item, err := b.OpenItem(keys, bp, unhex(c.OpenKey))
		if err != nil || item.Item.ID != c.Item {
			t.Fatalf("%s: %v %v", c.Name, item, err)
		}
	}
	limited, err := DecodeBlueprint(unhex(f.Blueprints["limited"].Hex))
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range f.Capped {
		b, err := DecodeBox(unhex(c.Box))
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		drawn, err := b.OpenItem(keys, limited, unhex(c.OpenKey))
		if err != nil || drawn.Item.ID != c.Item || drawn.Serial != c.Serial {
			t.Fatalf("%s: %v %v", c.Name, drawn, err)
		}
	}
	for name, s := range f.Invalid.Undecodable {
		if _, err := DecodeBox(unhex(s)); err == nil {
			t.Fatalf("%s: decoded", name)
		}
	}
	for name, s := range f.Invalid.BadSignature {
		b, err := DecodeBox(unhex(s))
		if err == nil && b.Verify(keys) == nil {
			t.Fatalf("%s: verified", name)
		}
	}
	for name, s := range f.Invalid.WrongKey {
		if _, err := first.Open(keys, unhex(s)); err == nil {
			t.Fatalf("%s: opened", name)
		}
	}
}
